/**
 * Служебные пометки из контекста иногда протекают в готовый текст, несмотря на
 * прямой запрет в промпте. Чистим уже после генерации — на инструкцию полагаться нельзя.
 */
// \b в JavaScript не знает кириллицы, поэтому границы слова задаём явно.
const CYR = "А-Яа-яЁё";
const word = (w: string) => new RegExp(`(?<![${CYR}A-Za-z])${w}(?![${CYR}A-Za-z])`, "g");

const LEAK_PATTERNS: [RegExp, string][] = [
  [/\[НАШ:?\s*[^\]]*\]\s*/g, ""],
  [/\((?:наш|наши|наша)\)\s*/gi, ""],
  [word("МЫ"), "мы"],
  [word("ОНИ"), "они"],
  [word("НАШИ"), "наши"],
  [word("НАШ"), "наш"],
  [/посчитано кодом[:,]?\s*/gi, ""],
  [/нетворс\/мин/gi, "золота в минуту"],
  [word("LVP"), "худший"],
  [word("MVP"), "MVP"],
];

/** Убирает служебные метки и капс, протёкшие из контекста в готовый разбор. */
export function sanitizeAnalysis(text: string): string {
  let out = text;
  for (const [pattern, replacement] of LEAK_PATTERNS) {
    out = out.replace(pattern, replacement as string);
  }
  // Стрелочная нотация чисел (6843->21819) — тоже машинный след.
  out = out.replace(/(\d)\s*->\s*(\d)/g, "$1 → $2");
  // После вырезания меток остаются двойные пробелы и пробел перед знаками препинания.
  out = out.replace(/ {2,}/g, " ").replace(/ +([,.!?:;])/g, "$1");
  return out.replace(/\n{3,}/g, "\n\n").trim();
}
