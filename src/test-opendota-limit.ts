import assert from 'node:assert/strict';
import {OpenDotaLimit} from './opendota-limit.js';
const limit = new OpenDotaLimit();
assert.deepEqual([limit.reserve(1000), limit.reserve(1000), limit.reserve(1000)], [0,1500,3000], 'concurrent consumers get distinct slots');
limit.response(429,null,1000);
assert(limit.limited(900999));
assert(!limit.limited(901000));
limit.response(429,null,901000);
assert(limit.limited(2700999), 'repeated throttling doubles cooldown');
limit.response(200,null,2701000);
limit.response(429,'3600',2701000);
assert(limit.limited(6300999), 'Retry-After can extend cooldown');
assert(!limit.limited(6301000));
limit.response(200,null,6301000);
limit.response(429,null,6301000);
assert(!limit.limited(7201000), 'success resets exponential backoff');
limit.response(429,new Date(10801000).toUTCString(),7201000);
limit.networkFailure(7201001);
assert(limit.limited(10800999), 'network failure never shortens server cooldown');
console.log('OpenDota limiter tests passed');
